const MPEG1_LAYER_III_128_KBPS_FRAME_BYTES = 417;
const MPEG1_LAYER_III_HEADER = [0xff, 0xfb, 0x90, 0x64];

function createMpegFrame(fill: number) {
  const frame = new Uint8Array(MPEG1_LAYER_III_128_KBPS_FRAME_BYTES).fill(
    fill,
  );
  frame.set(MPEG1_LAYER_III_HEADER);
  return frame;
}

export const mp3Bytes = new Uint8Array(
  MPEG1_LAYER_III_128_KBPS_FRAME_BYTES * 2,
);
mp3Bytes.set(createMpegFrame(0x11), 0);
mp3Bytes.set(
  createMpegFrame(0x22),
  MPEG1_LAYER_III_128_KBPS_FRAME_BYTES,
);

